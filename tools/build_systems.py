for sid in ['s1', 's2', 's3', 's4', 's5', 's6']:
    imgs = []
    for im in ATLAS[sid]:
        w, h = Image.open(os.path.join(IMG, im['file'] + '.jpg')).size
        P = lambda v, d: round(100 * v / d, 2)
        box = lambda b: [P(b[0], w), P(b[1], h), P(b[2] - b[0], w), P(b[3] - b[1], h)] if b else None
        spots = [dict(ru=s['ru'], la=s['la'], gr=s['gr'], row=s['row'], x=P(s['x'], w), y=P(s['y'], h), box=box(s['box'])) for s in im['spots']]
        full = im['kind'] == 'schema' and os.path.exists(os.path.join(IMG, im['file'] + '_full.jpg'))
        imgs.append(dict(src='img/systems/' + im['file'] + '.jpg', full=('img/systems/' + im['file'] + '_full.jpg') if full else None, kind=im['kind'], title=im['title'], w=w, h=h,
                         masks=[box(m) for m in im['masks']], spots=spots))
    systems.append(dict(id=sid, title=titles[sid], icon=icons[sid], images=imgs, wf=WF[sid]))
